/**
 * Transform raw document data used into the collaboration model in snake_case
 * from the collaboration service's response to a camelCase object.
 */
const transformDocument = (rawDocument: any): LegacyCollaborationDocument => ({
  id: rawDocument.id,
  name: rawDocument.name,
  createdAt: rawDocument.created_at,
  updatedAt: rawDocument.updated_at,
  deletedAt: rawDocument.deleted_at,
  reasonRejection: rawDocument.rejection_reason,
  // server response pending status as null
  status: rawDocument.collaborator_status || 'pending',
  fileExt: rawDocument.file_ext,
});

/**
 * Transform a raw invitation data from response of the backend in snake_case
 * to a camelCase objects.
 */
const transformInvitation = (rawInvitation: any): CollaborationInvitation => ({
  id: rawInvitation.id,
  status: rawInvitation.status,
  collaborator: {
    id: rawInvitation.collaborator.id,
    email: rawInvitation.collaborator.email,
    firstName: rawInvitation.collaborator.first_name,
    lastName: rawInvitation.collaborator.last_name,
    phoneNumber: rawInvitation.collaborator.phone_number,
  },
  documents: ((rawInvitation.documents as any[]) ?? []).map(transformDocument),
});

